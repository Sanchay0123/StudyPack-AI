"""Lecture Notes viewer: topic navigation, search, provenance, source tracing, examples, diagrams, versions."""
from __future__ import annotations

import streamlit as st

from export.markdown_exporter import render_examples, render_notes
from prompt_engine.prompt_router import RESOURCE_LABELS
from ui.common import get_repo, hero, local_time, pill, require_project
from ui.components import empty_state, mermaid, render_note_section
from ui.notes_editor import render_editor


def _search(project_id: str, parents, query: str) -> None:
    repo = get_repo()
    q = query.lower()
    hits = 0
    for p in parents:
        res = repo.get_resource(project_id, p.topic_id, "notes")
        if not res:
            continue
        for s in res.content.get("sections", []):
            if q in s["heading"].lower() or q in s.get("content", "").lower():
                hits += 1
                content = s.get("content", "")
                idx = content.lower().find(q)
                snippet = content[max(0, idx - 80): idx + 160] if idx >= 0 else content[:200]
                st.markdown(f"**{p.title} › {s['heading']}**  \n…{snippet}…")
    if not hits:
        st.caption("No matches.")


def render() -> None:
    project = require_project()
    repo = get_repo()
    parents = [t for t in repo.list_topics(project.project_id) if t.parent_topic_id is None]
    hero(project.name, "Comprehensive notes with provenance: blue = from your documents, amber = supplementary explanation, "
                       "red = inferred.", "Lecture Notes")
    if not parents:
        empty_state("No topics yet - run the analysis and generate notes first.")
        return
    query = st.text_input("Search the notes", placeholder="Search all topics...", label_visibility="collapsed")
    if query.strip():
        st.subheader(f"Results for “{query}”")
        _search(project.project_id, parents, query.strip())
        st.divider()

    have_notes = {p.topic_id for p in parents if repo.get_resource(project.project_id, p.topic_id, "notes")}
    left, right = st.columns([1, 3], gap="large")
    with left:
        st.markdown("**Topics**")
        topic_id = st.radio("Topic", [p.topic_id for p in parents], label_visibility="collapsed",
                            format_func=lambda i: next(p.title for p in parents if p.topic_id == i) + ("  ✓" if i in have_notes else ""),
                            key="notes_topic")
        st.caption("✓ = notes generated")
    topic = next(p for p in parents if p.topic_id == topic_id)
    with right:
        st.markdown(f"## {topic.title}")
        subs = [t.title for t in repo.list_topics(project.project_id) if t.parent_topic_id == topic.topic_id]
        if subs:
            st.markdown(" ".join(pill(s, "muted") for s in subs), unsafe_allow_html=True)
        if topic.learning_objectives:
            with st.expander("Learning objectives", expanded=False):
                st.markdown("\n".join(f"- {o}" for o in topic.learning_objectives))
        tabs = st.tabs(["Notes", "Worked examples", "Diagrams"])
        chunk_text = {c.chunk_id: c.content for c in repo.list_chunks(project.project_id)}
        with tabs[0]:
            versions = repo.resource_versions(project.project_id, topic.topic_id, "notes")
            if not versions:
                empty_state("Notes have not been generated for this topic yet (Generation Center).")
            else:
                if len(versions) > 1:
                    v = st.selectbox("Version", versions, format_func=lambda r: f"v{r.version} · {r.origin} · {local_time(r.created_at)}"
                                     + (" (current)" if r.is_current else ""))
                else:
                    v = versions[0]
                notes = v.content
                origin = {"edited": "Edited by you; generated by", "refined": "Refined by"}.get(v.origin, "Generated by")
                st.caption(f"{origin} {v.model} via {v.provider} · prompt {v.prompt_id}@{v.prompt_version}")
                if st.session_state.pop("_close_notes_editor", False):
                    st.session_state["notes_edit_mode"] = False
                if v.is_current and st.toggle("Edit these notes", key="notes_edit_mode"):
                    render_editor(repo, v)
                    return
                meta = notes.get("_meta", {})
                if meta.get("truncated"):
                    st.warning(f"The source for this topic exceeded the model's context budget; notes used "
                               f"{meta.get('source_chunks_used')} of {meta.get('source_chunks_total')} source chunks.")
                if meta.get("change_log"):
                    with st.expander("Refinement changes in this version"):
                        st.markdown("\n".join(f"- {c}" for c in meta["change_log"]))
                st.markdown(notes.get("overview", ""))
                for s in notes.get("sections", []):
                    render_note_section(s, notes.get("_sources", {}), chunk_text, highlight=query.strip())
                if notes.get("key_terms"):
                    st.markdown("#### Key terms")
                    st.dataframe([{"Term": t["term"], "Definition": t["definition"]} for t in notes["key_terms"]],
                                 hide_index=True, use_container_width=True)
                st.markdown("#### Summary")
                st.markdown(notes.get("summary", ""))
                st.download_button("Download these notes (Markdown)", f"# {topic.title}\n\n" + render_notes(notes),
                                   file_name=f"{topic.title}.md", mime="text/markdown")
        with tabs[1]:
            ex = repo.get_resource(project.project_id, topic.topic_id, "examples")
            if not ex:
                empty_state(f"{RESOURCE_LABELS['examples']} not generated yet.")
            else:
                for i, e in enumerate(ex.content.get("examples", []), 1):
                    with st.container(border=True):
                        st.markdown(f"**Example {i}: {e['title']}** <span class='sp-ref'>{e['example_type']}</span>", unsafe_allow_html=True)
                        st.markdown(f"**Problem.** {e['problem']}")
                        st.markdown("\n".join(f"{n}. {step}" for n, step in enumerate(e.get("steps", []), 1)))
                        st.markdown(f"**Answer.** {e['answer']}")
                        st.caption(e["explanation"])
                st.download_button("Download examples (Markdown)", render_examples(ex.content), file_name=f"{topic.title} - examples.md")
        with tabs[2]:
            dg = repo.get_resource(project.project_id, topic.topic_id, "diagrams")
            if not dg:
                empty_state(f"{RESOURCE_LABELS['diagrams']} not generated yet.")
            else:
                if not dg.content.get("diagrams"):
                    st.info(f"No diagram for this topic: {dg.content.get('no_diagram_reason') or 'not applicable'}")
                for i, d in enumerate(dg.content.get("diagrams", [])):
                    st.markdown(f"**{d['title']}** <span class='sp-ref'>{d['diagram_type']}</span>", unsafe_allow_html=True)
                    mermaid(d["mermaid"], height=420, key=f"{topic.topic_id[-6:]}{i}")
                    st.caption(d["caption"])
                    with st.expander("Mermaid source"):
                        st.code(d["mermaid"], language="text")
