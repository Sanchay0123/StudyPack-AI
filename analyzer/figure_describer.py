"""P00 - describe extracted figures with a vision-capable model.

Each description replaces the figure's marker in the source text, prefixed with an explicit label saying it was
generated by the model and must be verified. The chunk is flagged `needs_review` with low extraction confidence,
so downstream prompts see it as uncertain source material (format_source adds "[low extraction confidence - verify]").
"""
from __future__ import annotations

import io
from typing import Callable

from config.logging_config import get_logger
from prompt_engine.prompt_builder import neutralize_source_text
from prompt_engine.stage_runner import StageError, StageRunner
from providers.exceptions import ProviderError
from storage.repository import Repository

log = get_logger("analyzer.figures")
MAX_IMAGE_SIDE = 1024  # keeps vision token cost and memory bounded on a 6 GB GPU
FIGURE_CONFIDENCE = 0.5


def load_image_bytes(path: str, max_side: int = MAX_IMAGE_SIDE) -> bytes:
    from PIL import Image

    with Image.open(path) as img:
        img = img.convert("RGB")
        img.thumbnail((max_side, max_side))
        buf = io.BytesIO()
        img.save(buf, format="PNG")
        return buf.getvalue()


def description_block(figure: dict, d: dict) -> str:
    where = f"page {figure['page']}" if figure.get("page") else (f"slide {figure['slide']}" if figure.get("slide") else "document")
    if d["educational_relevance"] == "low":
        return f"[Figure {figure['id']} on {where}: {d['figure_kind'].replace('_', ' ')} with no educational content (described by the vision model)]"
    parts = [f"[Figure {figure['id']} on {where} - description generated by the vision model; verify against the original document]",
             f"{d['figure_kind'].replace('_', ' ').capitalize()}: {d['description']}"]
    if d.get("key_elements"):
        parts.append("Key elements: " + "; ".join(d["key_elements"]) + ".")
    if d.get("text_in_image"):
        parts.append(f"Text in the figure: \"{d['text_in_image']}\".")
    if d.get("uncertain_parts"):
        parts.append(f"Unclear in the image: {d['uncertain_parts']}.")
    return " ".join(parts)


def pending_figures(repo: Repository, project_id: str) -> list[tuple[object, dict]]:
    out = []
    for doc in repo.list_documents(project_id):
        for fig in doc.metadata.get("figures", []) or []:
            if not fig.get("description"):
                out.append((doc, fig))
    return out


def describe_figures(repo: Repository, runner: StageRunner, project_id: str, subject: str = "",
                     progress: Callable[[str, float], None] = lambda m, f: None) -> dict:
    todo = pending_figures(repo, project_id)
    stats = {"total": len(todo), "described": 0, "low_relevance": 0, "failed": 0, "errors": []}
    chunks = repo.list_chunks(project_id)
    for i, (doc, fig) in enumerate(todo):
        progress(f"Describing figure {fig['id']} of {doc.filename} ({i + 1}/{len(todo)})", i / max(len(todo), 1))
        holder = next((c for c in chunks if c.document_id == doc.document_id and fig["marker"] in c.content), None)
        nearby = holder.content.replace(fig["marker"], "")[:1200] if holder else ""
        where = f"page {fig['page']}" if fig.get("page") else (f"slide {fig['slide']}" if fig.get("slide") else "document")
        try:
            result = runner.run("figure_description", {
                "subject": subject or "the course", "document_name": doc.filename, "location": where,
                "nearby_text": neutralize_source_text(nearby) or "(none)",
                "caption_note": f"Author-provided alt text / caption: {fig['caption']}" if fig.get("caption") else "",
            }, images=[load_image_bytes(fig["path"])])
        except (StageError, ProviderError, OSError) as exc:
            stats["failed"] += 1
            stats["errors"].append(f"{doc.filename} {fig['id']}: {exc.__class__.__name__}: {str(exc)[:200]}")
            log.warning("Figure %s of %s failed: %s", fig["id"], doc.filename, exc)
            continue
        d = result.output.model_dump()
        fig["description"] = {**d, "model": result.model, "prompt": f"{result.template_id}@{result.version}"}
        block = description_block(fig, d)
        if holder is not None:
            holder.content = holder.content.replace(fig["marker"], block)
            repo.update_chunk_content(holder.chunk_id, holder.content, needs_review=True,
                                      confidence=min(holder.extraction_confidence, FIGURE_CONFIDENCE))
        repo.update_document_status(doc.document_id, doc.processing_status, doc.metadata)
        stats["described"] += 1
        stats["low_relevance"] += d["educational_relevance"] == "low"
    progress("Figures done.", 1.0)
    if stats["described"]:
        repo.log_activity(project_id, f"Described {stats['described']} figure(s) with the vision model")
    return stats
