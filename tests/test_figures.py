def test_pdf_figures_saved_and_icons_skipped(tmp_path):
    res = extract_pdf(str(fb.make_pdf_with_figure(tmp_path / "fig.pdf")))
    figs = res.metadata["figures"]
    assert len(figs) == 1 and Path(figs[0]["path"]).exists() and figs[0]["page"] == 1
    assert any(b.content_type == "image_ref" and b.text == figs[0]["marker"] for b in res.blocks)


def test_pptx_and_docx_figures_saved(tmp_path):
    pptx = extract_pptx(str(fb.make_pptx_with_figure(tmp_path / "f.pptx")))
    assert len(pptx.metadata["figures"]) == 1 and pptx.metadata["figures"][0]["slide"] == 1
    docx = extract_docx(str(fb.make_docx_with_figure(tmp_path / "f.docx")))
    assert len(docx.metadata["figures"]) == 1 and Path(docx.metadata["figures"][0]["path"]).exists()


def test_ollama_sends_images_base64():
    session = FakeSession(post=FakeResponse(payload={"message": {"content": "{}"}, "done_reason": "stop"}))
    OllamaProvider(Settings(), session).generate(GenerationRequest(system="s", prompt="p", images=[b"\x89PNG..."]))
    assert session.last_json["messages"][1]["images"] == ["iVBORy4uLg=="]


def test_describe_figures_replaces_marker_with_labelled_description(tmp_path):
    from analyzer.figure_describer import describe_figures, pending_figures

    repo = Repository(Database(tmp_path / "f.db"))
    project = repo.create_project(Project(name="Figures"))
    pdf = fb.make_pdf_with_figure(tmp_path / "fig.pdf")
    ingest_files(repo, project.project_id, [("fig.pdf", pdf.read_bytes())], settings=get_settings())
    assert len(pending_figures(repo, project.project_id)) == 1
    fake = FakeLLM()
    stats = describe_figures(repo, StageRunner(ProviderRouter(fake), get_settings()), project.project_id, "Computing")
    assert stats == {"total": 1, "described": 1, "low_relevance": 0, "failed": 0, "errors": []}
    assert fake.calls[0].images and fake.calls[0].images[0].startswith(b"\x89PNG")
    text = " ".join(c.content for c in repo.list_chunks(project.project_id))
    assert "not yet described" not in text
    assert "description generated by the vision model; verify against the original document" in text
    assert "Three boxes labelled Input, Process and Output" in text
    holder = next(c for c in repo.list_chunks(project.project_id) if "vision model" in c.content)
    assert holder.needs_review and holder.extraction_confidence <= 0.5
    assert pending_figures(repo, project.project_id) == []
    assert repo.list_documents(project.project_id)[0].metadata["figures"][0]["description"]["figure_kind"] == "flowchart"
